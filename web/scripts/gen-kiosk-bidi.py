#!/usr/bin/env python3
"""Writes web/src/data/kioskBidi.ts: the strong bidi classes (L; R or AL) of every code point, from Python's
unicodedata, for the kiosk preview's label direction (docs/kiosk-background-scrim.md, Label lines, 6).

Unassigned code points have no bidi class here (unicodedata gives ''), so they are never strong: the spec skips
them (Cn), and with the table the answer depends on its own Unicode version only, not on the browser's.
Run with the Python whose Unicode version the table should have: python3 web/scripts/gen-kiosk-bidi.py
"""
import os
import sys
import unicodedata

# The version docs/kiosk-background-scrim.md's vectors follow (UAX #29 and the bidi classes of Unicode 15.1; Python 3.13
# has it).
UNICODE = '15.1.0'
if unicodedata.unidata_version != UNICODE:
    sys.exit(f'gen-kiosk-bidi.py: this Python has Unicode {unicodedata.unidata_version}; the table must be Unicode '
             f'{UNICODE}, the version the spec vectors assume. Run it with a Python that has {UNICODE}, '
             f'or change UNICODE together with the spec.')

runs = []  # (first, last, 'L' | 'R')
prev, start = None, 0
for cp in range(0x110000):
    b = unicodedata.bidirectional(chr(cp))
    k = 'L' if b == 'L' else 'R' if b in ('R', 'AL') else None
    if k != prev:
        if prev:
            runs.append((start, cp - 1, prev))
        prev, start = k, cp
if prev:
    runs.append((start, 0x10FFFF, prev))

# Each run: its class, then the gap from the previous run's end and its length less one, in base 36.
def b36(n):
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    s = ''
    while True:
        n, r = divmod(n, 36)
        s = digits[r] + s
        if n == 0:
            return s

tokens, end = [], -1
for first, last, k in runs:
    tokens.append(f'{k}{b36(first - end - 1)}.{b36(last - first)}')
    end = last
table = ','.join(tokens)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'kioskBidi.ts')
with open(out, 'w', encoding='ascii') as f:
    f.write(f"""// Generated by web/scripts/gen-kiosk-bidi.py from Unicode {unicodedata.unidata_version} (Python {sys.version.split()[0]}). Do not edit.
// The strong bidi classes for the kiosk preview's label direction (docs/kiosk-background-scrim.md, Label lines, 6):
// {len(runs)} runs of code points of class L, or R/AL. Unassigned code points are in none, so they are never strong.

/** Unicode version of the table. */
export const BIDI_UNICODE_VERSION = '{unicodedata.unidata_version}';

/** Runs, in order: class (L or R), gap from the previous run's end and length less one, base 36. */
const TABLE =
  '{table}';

let starts: Int32Array | null = null;
let ends: Int32Array | null = null;
let rtl: Uint8Array | null = null;

function decode(): void {{
  const tokens = TABLE.split(',');
  starts = new Int32Array(tokens.length);
  ends = new Int32Array(tokens.length);
  rtl = new Uint8Array(tokens.length);
  let end = -1;
  tokens.forEach((t, i) => {{
    const dot = t.indexOf('.');
    const first = end + 1 + parseInt(t.slice(1, dot), 36);
    end = first + parseInt(t.slice(dot + 1), 36);
    starts![i] = first;
    ends![i] = end;
    rtl![i] = t[0] === 'R' ? 1 : 0;
  }});
}}

/** A code point's strong bidi class: 'L', 'R' (R or AL), or null (not strong, or unassigned). */
export function strongBidiClass(cp: number): 'L' | 'R' | null {{
  if (!starts) decode();
  let lo = 0;
  let hi = starts!.length - 1;
  while (lo <= hi) {{
    const mid = (lo + hi) >> 1;
    if (cp < starts![mid]) hi = mid - 1;
    else if (cp > ends![mid]) lo = mid + 1;
    else return rtl![mid] ? 'R' : 'L';
  }}
  return null;
}}
""")
print(f'{len(runs)} runs, table {len(table)} bytes, Unicode {unicodedata.unidata_version}')
