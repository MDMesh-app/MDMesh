// The `@mdmesh/console` surface snapshots. A failure here means the public surface changed:
// - surface.txt: an export or a design token was added, removed or renamed;
// - surface.d.ts.txt: the shape of a public type, component or function changed (a slot contract's prop, an
//   optional field made required, a component's props).
// Adding is fine: update both with `npm test -- -u` and review the diff. Removing, renaming or changing a shape
// breaks forks: keep the old one for one release (@deprecated) and announce it in the CHANGELOG first.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, normalize } from 'node:path';
import { describe, expect, it } from 'vitest';
import * as sdk from '@mdmesh/console';

const read = (path: string) => readFileSync(join(import.meta.dirname, path), 'utf8');

/** The names sdk/index.ts exports, split into values and types. It must hold only `export { } from` statements. */
function declaredExports() {
  const code = read('index.ts')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');
  const statement = /export\s+(type\s+)?\{([^}]*)\}\s+from\s+'[^']+';/g;
  const values: string[] = [];
  const types: string[] = [];
  for (const [, isType, names] of code.matchAll(statement)) {
    for (const name of names.split(',').map((n) => n.trim()).filter(Boolean)) {
      (isType ? types : values).push(name.split(/\s+as\s+/).pop() as string);
    }
  }
  return { values: values.sort(), types: types.sort(), rest: code.replace(statement, '').trim() };
}

/** The design tokens: every custom property tokens.css declares. */
function tokens(): string[] {
  const names = [...read('../tokens.css').matchAll(/^\s*(--[a-z0-9-]+)\s*:/gm)].map((m) => m[1]);
  return [...new Set(names)].sort();
}

describe('@mdmesh/console', () => {
  const declared = declaredExports();

  it('is made of export-from statements only (so this test reads every export)', () => {
    expect(declared.rest).toBe('');
  });

  it('exports at runtime exactly the values sdk/index.ts declares', () => {
    expect(Object.keys(sdk).sort()).toEqual(declared.values);
  });

  it('matches the surface snapshot (sdk/surface.txt)', async () => {
    const lines = [
      '# @mdmesh/console public surface, EXTENSION_API_VERSION ' + sdk.EXTENSION_API_VERSION + '. Generated by',
      '# sdk/surface.test.ts: `npm test -- -u` rewrites it. See the stability rules in sdk/index.ts.',
      ...declared.values.map((n) => `value ${n}`),
      ...declared.types.map((n) => `type ${n}`),
      ...tokens().map((n) => `token ${n}`),
    ];
    await expect(lines.join('\n') + '\n').toMatchFileSnapshot('./surface.txt');
  });

  it('matches the type surface snapshot (sdk/surface.d.ts.txt)', async () => {
    const out = mkdtempSync(join(tmpdir(), 'mdmesh-sdk-dts-'));
    try {
      emitDeclarations(out);
      const header = [
        `// @mdmesh/console type surface, EXTENSION_API_VERSION ${sdk.EXTENSION_API_VERSION}: every public declaration and`,
        '// the types it uses, as tsc emits them (web/tsconfig.sdk.json). Generated by sdk/surface.test.ts:',
        '// `npm test -- -u` rewrites it. See the stability rules in sdk/index.ts.',
      ];
      await expect([...header, ...typeSurface(out)].join('\n') + '\n').toMatchFileSnapshot('./surface.d.ts.txt');
    } finally {
      rmSync(out, { recursive: true, force: true });
    }
  }, 60_000);
});

// ---- the type surface ----
//
// tsc emits the declarations of sdk/index.ts and every module it reaches (well under a second with TypeScript 7,
// which has no stable JS API, hence the CLI). The snapshot keeps only the declarations a fork can see: those
// sdk/index.ts re-exports, and whatever they name in turn, followed through imports. Declarations a public module
// keeps to itself stay out, so an internal change there never fails this test.

function emitDeclarations(out: string) {
  const tsc = join(dirname(createRequire(import.meta.url).resolve('typescript/package.json')), 'bin', 'tsc');
  const web = join(import.meta.dirname, '..', '..');
  const run = spawnSync(process.execPath, [tsc, '-p', join(web, 'tsconfig.sdk.json'), '--outDir', out], { encoding: 'utf8' });
  if (run.status !== 0) throw new Error(`tsc failed:\n${run.stdout}${run.stderr}`);
}

interface Module {
  /** Top-level statements, in order. tsc starts each at column 0; its continuation lines are indented or `}`. */
  statements: string[];
  /** Local name -> where it comes from: an import, or an `export { x as y } from` re-export. */
  links: Map<string, { from: string; name: string }>;
  /** Local name -> the statements declaring it (several for overloads). */
  declared: Map<string, number[]>;
}

const DECLARATION = /^(?:export\s+)?(?:declare\s+)?(?:const|let|var|function|class|interface|type|enum|namespace)\s+([\w$]+)/;
const FROM = /^(?:import|export)\s+(?:type\s+)?\{([^}]*)\}\s+from\s+'([^']+)';$/;

function typeSurface(out: string): string[] {
  const modules = new Map<string, Module | null>();
  const load = (key: string): Module | null => {
    if (!modules.has(key)) modules.set(key, parse(out, key));
    return modules.get(key) ?? null;
  };
  const kept = new Map<string, Set<number>>();
  const need = (key: string, name: string) => {
    const module = load(key);
    if (!module) return; // a package (react, react-router): not ours to snapshot
    const link = module.links.get(name);
    if (link) return need(link.from, link.name);
    for (const index of module.declared.get(name) ?? []) {
      const seen = kept.get(key) ?? new Set<number>();
      kept.set(key, seen);
      if (seen.has(index)) continue;
      seen.add(index);
      const code = module.statements[index];
      for (const [, spec, imported] of code.matchAll(/import\("([^"]+)"\)\.([\w$]+)/g)) {
        if (spec.startsWith('.')) need(resolveModule(key, spec), imported);
      }
      const words = new Set(code.replace(/'[^']*'|"[^"]*"/g, '').match(/[A-Za-z_$][\w$]*/g));
      for (const word of words) if (word !== name && (module.declared.has(word) || module.links.has(word))) need(key, word);
    }
  };

  const entry = load('sdk/index') as Module;
  for (const name of entry.links.keys()) need('sdk/index', name);
  const lines = entry.statements.filter((s) => !s.startsWith('import '));
  for (const key of [...kept.keys()].filter((k) => k !== 'sdk/index').sort()) {
    const module = modules.get(key) as Module;
    lines.push('', `// ---- ${key} ----`, ...[...(kept.get(key) as Set<number>)].sort((a, b) => a - b).map((i) => module.statements[i]));
  }
  return lines;
}

/** `ui/Button` and `./Card` -> `ui/Card`. */
function resolveModule(from: string, spec: string): string {
  return normalize(join(dirname(from), spec)).replace(/\\/g, '/').replace(/\.(?:d\.)?tsx?$|\.js$/, '');
}

function parse(out: string, key: string): Module | null {
  if (key.startsWith('..')) return null; // outside the emitted tree
  let code: string;
  try {
    code = readFileSync(join(out, `${key}.d.ts`), 'utf8');
  } catch {
    try {
      code = readFileSync(join(out, key, 'index.d.ts'), 'utf8');
    } catch {
      return null;
    }
  }
  const statements: string[] = [];
  for (const line of code.split('\n')) {
    if (!line.trim()) continue;
    if (/^[^\s}]/.test(line) || !statements.length) statements.push(line);
    else statements[statements.length - 1] += `\n${line}`;
  }
  const module: Module = { statements: [], links: new Map(), declared: new Map() };
  for (const statement of statements) {
    if (/^import '/.test(statement) || statement === 'export {};') continue; // CSS side effects, module markers
    const index = module.statements.push(statement) - 1;
    const from = FROM.exec(statement.replace(/\s+/g, ' ').replace(/ ?\} ?from/, ' } from'));
    if (from) {
      const [, names, spec] = from;
      for (const part of names.split(',').map((n) => n.trim().replace(/^type\s+/, '')).filter(Boolean)) {
        const [imported, local = imported] = part.split(/\s+as\s+/);
        module.links.set(local, { from: spec.startsWith('.') ? resolveModule(key, spec) : spec, name: imported });
      }
      continue;
    }
    const name = DECLARATION.exec(statement)?.[1];
    if (name) module.declared.set(name, [...(module.declared.get(name) ?? []), index]);
  }
  return module;
}
